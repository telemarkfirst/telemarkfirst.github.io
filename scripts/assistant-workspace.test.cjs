const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.join(__dirname, '../src/telemark/assistantWorkspace.ts'), 'utf8');
const {outputText} = ts.transpileModule(source, {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022}});
const loaded = {};
new Function('exports', outputText)(loaded);
const {emptyWorkspace, loadAssistantWorkspace, saveAssistantWorkspace} = loaded;
const backing = new Map();
global.sessionStorage = {getItem: (key) => backing.get(key) ?? null, setItem: (key, value) => backing.set(key, value)};
let checks = 0;
const workspace = {...emptyWorkspace(), draft: 'Why does this stop?', mode: 'hint', files: [{name: 'Main.java', source: 'motor.setPower(0);'}], errorText: 'Does not move', attempt: 'Checked the name'};
assert.equal(saveAssistantWorkspace('/docs/one', workspace), true);
assert.deepEqual(loadAssistantWorkspace('/docs/one'), workspace); checks++;
assert.deepEqual(loadAssistantWorkspace('/docs/two'), emptyWorkspace()); checks++;
workspace.files[0].source = 'Changed after save';
assert.equal(loadAssistantWorkspace('/docs/one').files[0].source, 'motor.setPower(0);'); checks++;
assert.equal(saveAssistantWorkspace('/docs/one', {...workspace, pasted: 'x'.repeat(16001)}), false); checks++;
for (let i = 0; i < 14; i++) saveAssistantWorkspace(`/lesson/${i}`, {...emptyWorkspace(), draft: String(i)});
assert.equal(JSON.parse(backing.values().next().value).length, 10); checks++;
assert.deepEqual(loadAssistantWorkspace('/docs/one'), emptyWorkspace()); checks++;
backing.set('telemark:assistant-workspaces:v1', JSON.stringify([null, {path:'/bad',workspace:{draft:'hi'}}]));
assert.deepEqual(loadAssistantWorkspace('/bad'), emptyWorkspace()); checks++;
global.sessionStorage = {getItem: () => {throw Error('denied');}, setItem: () => {throw Error('denied');}};
assert.deepEqual(loadAssistantWorkspace('/docs/one'), emptyWorkspace());
assert.equal(saveAssistantWorkspace('/docs/one', emptyWorkspace()), false); checks++;
console.log(`Assistant workspace recovery tests passed (${checks} cases)`);
