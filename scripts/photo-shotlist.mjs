import {readdirSync, readFileSync, writeFileSync, statSync} from 'node:fs';
import path from 'node:path';

/**
 * Generates PHOTO-SHOTLIST.md from the LessonPhoto slots in the lessons.
 *
 * The shot list is derived rather than maintained by hand, so it cannot drift
 * from the lessons. Slots that already have a src are reported as done.
 */

const root = process.cwd();

function walk(dir) {
  return readdirSync(dir, {withFileTypes: true}).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : [full];
  });
}

const files = walk(path.join(root, 'mechanical')).filter((f) => f.endsWith('.mdx'));
const rows = [];

for (const file of files) {
  const text = readFileSync(file, 'utf8');
  const title = text.match(/^title:\s*"(.*?)"/m)?.[1] ?? path.basename(file);
  for (const match of text.matchAll(/<LessonPhoto\b([\s\S]*?)\/>/g)) {
    const block = match[1];
    const prop = (name) => block.match(new RegExp(`${name}="([^"]*)"`))?.[1] ?? '';
    rows.push({
      lesson: title,
      file: path.relative(root, file),
      shot: prop('shot'),
      framing: prop('framing'),
      done: Boolean(prop('src')),
    });
  }
}

const outstanding = rows.filter((r) => !r.done);

const md = `# Photograph shot list

Generated by \`npm run photos:shotlist\`. Do not edit by hand; edit the
\`<LessonPhoto>\` slots in the lessons and regenerate.

Every entry below is a real thing to photograph on your own robot or in your own
shop. These are deliberately not illustrations: a real stripped thread or a real
bound slide is recognisable at a glance once seen, and a drawing of one is not.

**${outstanding.length} of ${rows.length} photographs still needed.**

## How to add one

1. Take the photograph. Phone cameras are fine; light and framing matter more
   than resolution.
2. Save it to \`static/img/mechanical/\` with a descriptive name.
3. Add \`src="img/mechanical/your-file.jpg"\` to the matching
   \`<LessonPhoto>\` slot, and set \`credit\` if you want attribution.
4. Run \`npm run photos:shotlist\` to update this file.

Until a slot has a \`src\`, the lesson renders the request itself, so the gap is
visible to readers rather than silently missing.

## Still needed

${outstanding
  .map(
    (r, i) => `### ${i + 1}. ${r.shot}

- **Lesson:** ${r.lesson}
- **Framing:** ${r.framing}
- **File:** \`${r.file}\`
`,
  )
  .join('\n')}
${rows.length === outstanding.length ? '' : `## Supplied\n\n${rows.filter((r) => r.done).map((r) => `- ${r.shot} (${r.lesson})`).join('\n')}\n`}`;

writeFileSync(path.join(root, 'PHOTO-SHOTLIST.md'), md);
console.log(`Wrote PHOTO-SHOTLIST.md: ${outstanding.length} of ${rows.length} photographs outstanding`);
